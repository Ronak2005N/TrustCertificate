/**
 * Lightweight timing instrumentation for the certificate issuance pipeline.
 *
 * Uses performance.now() (sub-millisecond resolution). Records stage
 * durations only — never secrets, private keys, tokens, or certificate
 * PII (no recipient names, emails, or course titles). Certificate IDs,
 * transaction hashes and IPFS CIDs are public on-chain values and are
 * safe to record.
 *
 * Stages measured inside issueCertificate (sequential):
 *   fingerprint → pdf → ipfs → blockchainPreparation →
 *   blockchainSubmission → blockchainConfirmation
 *
 * supabasePersistence is fire-and-forget in the real issuance flow
 * (issueCertificate returns before the insert settles); it is measured
 * separately and is NOT part of totalIssuanceMs.
 *
 * qrGenerationMs is always null here: QR codes are generated by the
 * CertificatePreview React component after issuance completes and are
 * not part of the issuance transaction path.
 */

export type IssuanceStage =
  | "fingerprint"
  | "pdf"
  | "ipfs"
  | "blockchainPreparation"
  | "blockchainSubmission"
  | "blockchainConfirmation"
  | "supabasePersistence";

export interface IssuanceTimings {
  certificateId: string;
  fingerprintGenerationMs: number;
  pdfGenerationMs: number;
  ipfsUploadMs: number;
  blockchainPreparationMs: number;
  blockchainSubmissionMs: number;
  blockchainConfirmationMs: number;
  /** Fire-and-forget stage; null until the Supabase insert settles. */
  supabasePersistenceMs: number | null;
  /** Always null — QR generation is render-time, not part of issuance. */
  qrGenerationMs: null;
  totalIssuanceMs: number;
  transactionHash: string;
  cid: string;
}

export interface IssuanceFailureRecord {
  certificateId: string;
  failedStage: IssuanceStage | "initialization";
  errorCategory: string;
  transactionSubmitted: boolean;
  transactionHash: string | null;
  totalMsUntilFailure: number;
}

const STAGE_FIELDS: Record<IssuanceStage, keyof IssuanceTimings> = {
  fingerprint: "fingerprintGenerationMs",
  pdf: "pdfGenerationMs",
  ipfs: "ipfsUploadMs",
  blockchainPreparation: "blockchainPreparationMs",
  blockchainSubmission: "blockchainSubmissionMs",
  blockchainConfirmation: "blockchainConfirmationMs",
  supabasePersistence: "supabasePersistenceMs",
};

export class IssuanceTimer {
  readonly #epoch: number;
  readonly #stageStarts = new Map<IssuanceStage, number>();
  readonly #stageDurations = new Map<IssuanceStage, number>();
  #certificateId = "";
  #failure: IssuanceFailureRecord | null = null;
  #timings: IssuanceTimings | null = null;

  constructor() {
    this.#epoch = performance.now();
  }

  startStage(stage: IssuanceStage): void {
    if (this.#stageStarts.has(stage)) {
      throw new Error(`Issuance stage already started: ${stage}`);
    }
    this.#stageStarts.set(stage, performance.now());
  }

  endStage(stage: IssuanceStage): void {
    const start = this.#stageStarts.get(stage);
    if (start === undefined) {
      throw new Error(`Issuance stage not started: ${stage}`);
    }
    this.#stageStarts.delete(stage);
    this.#stageDurations.set(stage, performance.now() - start);
  }

  hasOpenStage(stage: IssuanceStage): boolean {
    return this.#stageStarts.has(stage);
  }

  /** Record a duration measured outside startStage/endStage (e.g. fire-and-forget stages). */
  recordStageDuration(stage: IssuanceStage, durationMs: number): void {
    if (!Number.isFinite(durationMs) || durationMs < 0) {
      throw new Error(`Invalid stage duration for ${stage}: ${durationMs}`);
    }
    this.#stageDurations.set(stage, durationMs);
  }

  stageMs(stage: IssuanceStage): number | null {
    return this.#stageDurations.get(stage) ?? null;
  }

  elapsedMs(): number {
    return performance.now() - this.#epoch;
  }

  setCertificateId(id: string): void {
    this.#certificateId = id;
  }

  get certificateId(): string {
    return this.#certificateId;
  }

  get failure(): IssuanceFailureRecord | null {
    return this.#failure;
  }

  get timings(): IssuanceTimings | null {
    return this.#timings;
  }

  /** Build (and remember) a failure record. Does not throw. */
  fail(input: {
    failedStage: IssuanceStage | "initialization";
    errorCategory: string;
    transactionSubmitted: boolean;
    transactionHash?: string | null;
  }): IssuanceFailureRecord {
    const record: IssuanceFailureRecord = {
      certificateId: this.#certificateId,
      failedStage: input.failedStage,
      errorCategory: input.errorCategory,
      transactionSubmitted: input.transactionSubmitted,
      transactionHash: input.transactionHash ?? null,
      totalMsUntilFailure: this.elapsedMs(),
    };
    this.#failure = record;
    return record;
  }

  /**
   * Build the success record. totalIssuanceMs is measured at this moment
   * (issueCertificate is about to return). supabasePersistenceMs starts
   * as null and is filled in when the non-blocking stage settles.
   */
  success(input: { transactionHash: string; cid: string }): IssuanceTimings {
    for (const stage of Object.keys(STAGE_FIELDS) as IssuanceStage[]) {
      if (this.#stageStarts.has(stage)) {
        throw new Error(`Cannot finalize issuance timings: stage still open: ${stage}`);
      }
    }
    const timings: IssuanceTimings = {
      certificateId: this.#certificateId,
      fingerprintGenerationMs: this.#stageDurations.get("fingerprint") ?? Number.NaN,
      pdfGenerationMs: this.#stageDurations.get("pdf") ?? Number.NaN,
      ipfsUploadMs: this.#stageDurations.get("ipfs") ?? Number.NaN,
      blockchainPreparationMs: this.#stageDurations.get("blockchainPreparation") ?? Number.NaN,
      blockchainSubmissionMs: this.#stageDurations.get("blockchainSubmission") ?? Number.NaN,
      blockchainConfirmationMs: this.#stageDurations.get("blockchainConfirmation") ?? Number.NaN,
      supabasePersistenceMs: this.#stageDurations.get("supabasePersistence") ?? null,
      qrGenerationMs: null,
      totalIssuanceMs: this.elapsedMs(),
      transactionHash: input.transactionHash,
      cid: input.cid,
    };
    this.#timings = timings;
    return timings;
  }
}

/**
 * Wrap a single (usually promise-returning) operation: records the stage
 * duration and returns the operation's exact result, unaltered. The stage
 * is closed even when the operation throws.
 */
export async function measureStage<T>(
  timer: IssuanceTimer,
  stage: IssuanceStage,
  op: () => Promise<T> | T,
): Promise<T> {
  timer.startStage(stage);
  try {
    return await op();
  } finally {
    if (timer.hasOpenStage(stage)) timer.endStage(stage);
  }
}

// --- Module-level last-run state (for dev logging and harness access) ---

let lastTimings: IssuanceTimings | null = null;
let lastFailure: IssuanceFailureRecord | null = null;
let pendingNonBlocking: Promise<void> = Promise.resolve();
let logger: ((payload: Record<string, unknown>) => void) | null | undefined = undefined;

export function getLastIssuanceTimings(): IssuanceTimings | null {
  return lastTimings;
}

export function getLastIssuanceFailure(): IssuanceFailureRecord | null {
  return lastFailure;
}

/**
 * Wait for all fire-and-forget instrumented stages (Supabase persistence)
 * started so far to settle. Used by the measurement harness.
 */
export function waitForPendingNonBlockingStages(): Promise<void> {
  return pendingNonBlocking;
}

/**
 * Set a structured-log sink for timing events.
 * - undefined (default): console.info in dev builds only
 * - fn: custom sink
 * - null: silent
 */
export function setIssuanceTimingLogger(
  fn: ((payload: Record<string, unknown>) => void) | null,
): void {
  logger = fn;
}

function isDevBuild(): boolean {
  try {
    return Boolean((import.meta as { env?: Record<string, unknown> }).env?.["DEV"]);
  } catch {
    return false;
  }
}

function emit(payload: Record<string, unknown>): void {
  const sink =
    logger === undefined ? (isDevBuild() ? console.info.bind(console) : null) : logger;
  if (sink) sink(payload);
}

function roundMs(value: number | null): number | null {
  return value === null ? null : Math.round(value * 100) / 100;
}

/** Record a successful issuance. Returns the timings record. */
export function recordIssuanceSuccess(
  timer: IssuanceTimer,
  input: { transactionHash: string; cid: string },
): IssuanceTimings {
  const timings = timer.success(input);
  lastTimings = timings;
  lastFailure = null;
  emit({
    event: "issuance-success",
    certificateId: timings.certificateId,
    fingerprintGenerationMs: roundMs(timings.fingerprintGenerationMs),
    pdfGenerationMs: roundMs(timings.pdfGenerationMs),
    ipfsUploadMs: roundMs(timings.ipfsUploadMs),
    blockchainPreparationMs: roundMs(timings.blockchainPreparationMs),
    blockchainSubmissionMs: roundMs(timings.blockchainSubmissionMs),
    blockchainConfirmationMs: roundMs(timings.blockchainConfirmationMs),
    supabasePersistenceMs: roundMs(timings.supabasePersistenceMs),
    totalIssuanceMs: roundMs(timings.totalIssuanceMs),
    transactionHash: timings.transactionHash,
    cid: timings.cid,
  });
  return timings;
}

/** Record a failed issuance. Returns the failure record. Does not throw. */
export function recordIssuanceFailure(
  timer: IssuanceTimer,
  input: {
    failedStage: IssuanceStage | "initialization";
    errorCategory: string;
    transactionSubmitted: boolean;
    transactionHash?: string | null;
  },
): IssuanceFailureRecord {
  const record = timer.fail(input);
  lastFailure = record;
  emit({
    event: "issuance-failure",
    certificateId: record.certificateId,
    failedStage: record.failedStage,
    errorCategory: record.errorCategory,
    transactionSubmitted: record.transactionSubmitted,
    transactionHash: record.transactionHash,
    totalMsUntilFailure: roundMs(record.totalMsUntilFailure),
  });
  return record;
}

/**
 * Time a fire-and-forget stage (the promise is NOT awaited by the caller,
 * mirroring the app's non-blocking Supabase persistence). When the promise
 * settles, the duration is recorded and, for the Supabase stage, merged
 * into the last success record. Rejections are swallowed exactly like the
 * original `.catch(() => {})` behavior.
 */
export function trackNonBlockingStage(
  timer: IssuanceTimer,
  stage: IssuanceStage,
  op: Promise<unknown>,
): void {
  const start = performance.now();
  const settle = (): void => {
    timer.recordStageDuration(stage, performance.now() - start);
    const timings = timer.timings;
    if (stage === "supabasePersistence" && timings) {
      timings.supabasePersistenceMs = timer.stageMs(stage);
      if (lastTimings === timings) {
        emit({
          event: "issuance-non-blocking-stage",
          certificateId: timings.certificateId,
          stage,
          durationMs: roundMs(timings.supabasePersistenceMs),
        });
      }
    }
  };
  pendingNonBlocking = op.then(settle, settle);
}

/** Reset module-level state. For tests only. */
export function resetIssuanceTimingState(): void {
  lastTimings = null;
  lastFailure = null;
  pendingNonBlocking = Promise.resolve();
  logger = undefined;
}
